#!/usr/bin/env python3
"""Bake move-flame hues from each form's front.gif.

debug.html is opened as file://, where the browser cannot read sprite pixels.
FX.flameOf uses data/flame_hues.js instead. Missing slugs stay the classic orange fire.
Hue rules match FX._hueOf / FX._keepOrange in game/js/fx.js.
"""
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
DEX = ROOT / "data" / "monsterdex.js"
OUT = ROOT / "data" / "flame_hues.js"
SPRITE = ROOT / "monsterSprite"


def hue_of(path):
    im = Image.open(path)
    im.seek(0)
    im = im.convert("RGBA")
    w, h = im.size
    data = im.tobytes()
    step = 2 if w * h > 90000 else 1
    bins = [0] * 36
    n = 0
    for y in range(0, h, step):
        row = y * w * 4
        for x in range(0, w, step):
            i = row + x * 4
            r, g, b, a = data[i], data[i + 1], data[i + 2], data[i + 3]
            if a < 128:
                continue
            mx = r if r > g else g
            mx = mx if mx > b else b
            mn = r if r < g else g
            mn = mn if mn < b else b
            if mx < 40 or mn > 230:
                continue
            d = mx - mn
            if d < 28 or d / mx < 0.28:
                continue
            if mx == r:
                hue = ((g - b) / d) % 6
            elif mx == g:
                hue = (b - r) / d + 2
            else:
                hue = (r - g) / d + 4
            if hue < 0:
                hue += 6
            bins[int(hue * 6)] += 1
            n += 1
    if n < 24:
        return None
    best = max(range(36), key=lambda i: bins[i])
    if bins[best] < n * 0.18:
        return None
    return (best * 10 + 5) % 360


def keep_orange(h):
    return h <= 62 or h >= 348


def main():
    text = DEX.read_text(encoding="utf-8")
    start = text.find("window.ARENA_MONSTERDEX = ")
    if start < 0:
        raise SystemExit("ARENA_MONSTERDEX not found")
    dex, _ = json.JSONDecoder().raw_decode(text[text.find("[", start):])
    hues = {}
    missing = 0
    for p in dex:
        slug, directory = p["slug"], p["dir"]
        for shiny, name in ((False, "front.gif"), (True, "front-shiny.gif")):
            if shiny and not p.get("shiny"):
                continue
            path = SPRITE / directory / name
            if not path.is_file():
                missing += 1
                continue
            h = hue_of(path)
            if h is None or keep_orange(h):
                continue
            hues[slug + ("#s" if shiny else "")] = h
    keys = sorted(hues)
    body = ",".join(f"{json.dumps(k)}:{hues[k]}" for k in keys)
    OUT.write_text(
        "// Generated by tools/build_flame_hues.py — do not edit by hand.\n"
        "// slug → hue of front.gif. Missing slug = classic orange fire. \"#s\" is front-shiny.gif.\n"
        "window.ARENA_FLAME_HUES = {" + body + "};\n",
        encoding="utf-8",
    )
    print(f"forms {len(dex)}  stored {len(hues)}  missing-gif {missing}")
    for slug in ("charizard-mega-x", "charizard", "charmander", "magmar", "charizard-mega-y", "litwick"):
        print(f"  {slug}: {hues.get(slug, 'orange')}")


if __name__ == "__main__":
    main()
